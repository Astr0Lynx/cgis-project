"""pygeoapi PostgreSQL feature provider scoped to one catalog dataset.

Identical to pygeoapi's ``PostgreSQLProvider`` except that an optional
``static_filter`` (column -> value equality, generated by
:mod:`cgis_ogc.publish`, normally ``dataset_id`` AND ``dataset_version``) is
ANDed into every query, count, item lookup and prev/next neighbour, so several
catalog datasets and dataset versions can share one contract table
(``geo.admin_units``). Paging is ``ORDER BY unit_id`` within that scope, served
by the ``admin_units_identity`` index. Read-only: the publisher never sets
``editable``.
"""

from __future__ import annotations

import logging
from datetime import date, datetime

from pygeoapi.crs import get_transform_from_spec
from pygeoapi.provider.base import (
    ProviderConnectionError,
    ProviderInvalidQueryError,
    ProviderItemNotFoundError,
)
from pygeoapi.provider.sql import PostgreSQLProvider
from sqlalchemy import and_, true
from sqlalchemy.exc import SQLAlchemyError
from sqlalchemy.orm import Session

LOGGER = logging.getLogger(__name__)


def _is_instant(value: str) -> bool:
    try:
        if "T" in value or "t" in value:
            datetime.fromisoformat(value)
        else:
            date.fromisoformat(value)
        return True
    except ValueError:
        return False


def is_datetime_param(value: str) -> bool:
    """OGC 17-069r4 Req 26 D syntax: instant, or interval with optional '..' ends."""
    if "/" not in value:
        return _is_instant(value)
    parts = value.split("/")
    if len(parts) != 2:
        return False
    open_ends = [p in ("", "..") for p in parts]
    if all(open_ends):
        return True
    return all(o or _is_instant(p) for o, p in zip(open_ends, parts))


class CatalogPostgreSQLProvider(PostgreSQLProvider):

    def __init__(self, provider_def: dict):
        static_filter = dict(provider_def.get("static_filter") or {})
        super().__init__(provider_def)
        columns = self.table_model.__table__.columns.keys()
        unknown = sorted(set(static_filter) - set(columns))
        if unknown:
            raise ProviderConnectionError(f"static_filter columns not in table: {unknown}")
        self.static_filter = static_filter

    def get_fields(self):
        # Integration fix (Agent 6): pygeoapi's ``properties`` option limits the selected columns but
        # not ``fields``, which drive queryables and the OpenAPI query parameters. Agent 2's additive
        # admin_units columns include a JSONB column named ``properties``; published as a field it
        # duplicates the standard ``properties`` query parameter and makes /openapi invalid.
        fields = super().get_fields()
        if self.properties:
            keep = set(self.properties) | {self.id_field}
            for name in [n for n in fields if n not in keep]:
                del fields[name]
        return fields

    def _static_clause(self):
        if not self.static_filter:
            return true()
        return and_(*(getattr(self.table_model, column) == value
                      for column, value in self.static_filter.items()))

    def _get_cql_filters(self, filterq):
        return and_(self._static_clause(), super()._get_cql_filters(filterq))

    def _get_datetime_filter(self, datetime_):
        # OGC 17-069r4 /req/core/fc-time-response C: datetime matches every
        # feature that has no temporal geometry. pygeoapi raises (HTTP 500)
        # when no time_field is configured; the API layer has already
        # validated the parameter syntax.
        if self.time_field is None:
            if datetime_ not in (None, "../..") and not is_datetime_param(datetime_):
                raise ProviderInvalidQueryError(user_msg="datetime must be an RFC 3339 instant or interval")
            return true()
        return super()._get_datetime_filter(datetime_)

    def get(self, identifier, crs_transform_spec=None, **kwargs):
        """One feature of THIS collection, with collection-scoped ``prev``/``next`` neighbours.

        pygeoapi's own ``get`` looks the row up with ``Session.get`` on ``id_field`` and picks
        prev/next over the WHOLE table. Since database core/0007 the same ``unit_id`` exists once
        per (dataset, version), so that lookup could return another collection's (or another
        version's) row and point prev/next into other collections. Here the lookup and both
        neighbours carry the collection's static filter (dataset_id AND dataset_version), and a
        missing neighbour yields no link instead of a self-link.
        """
        id_column = getattr(self.table_model, self.id_field)
        scope = self._static_clause()
        with Session(self._engine) as session:
            try:
                item = (session.query(self.table_model)
                        .filter(id_column == identifier)
                        .filter(scope)
                        .first())
            except SQLAlchemyError as err:
                LOGGER.debug(err, exc_info=True)
                item = None
            if item is None:
                raise ProviderItemNotFoundError(f"No such item: {self.id_field}={identifier}.")
            feature = self._sqlalchemy_to_feature(item, get_transform_from_spec(crs_transform_spec))
            if self.properties:
                keep = set(self.properties)
                for key in [k for k in feature["properties"] if k not in keep]:
                    feature["properties"].pop(key)

            prev_item = (session.query(id_column).filter(scope).filter(id_column < identifier)
                         .order_by(id_column.desc()).first())
            next_item = (session.query(id_column).filter(scope).filter(id_column > identifier)
                         .order_by(id_column.asc()).first())
        if prev_item is not None:
            feature["prev"] = prev_item[0]
        if next_item is not None:
            feature["next"] = next_item[0]
        return feature

    def __repr__(self):
        return f"<CatalogPostgreSQLProvider> {self.table} {self.static_filter or ''}"
