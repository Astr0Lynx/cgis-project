# Deterministic SYNTHETIC Level 2 inputs (two towns, LULC raster, legend, optional Level 1) for tests and demos.

import csv
from math import floor
import os
from pathlib import Path

from affine import Affine
import numpy as np
from pyproj import Transformer
import rasterio
from shapely.geometry import box, mapping
from shapely.ops import transform

from ingestion.importer import sha256_file

from .grid import CRS, PIXEL
from .pipeline import _write_json


# Writes a single-band EPSG:6933 GeoTIFF; used by make_fixture and tests.
def _write_raster(path, values, affine, nodata):
    with rasterio.open(path, "w", driver="GTiff", width=values.shape[1], height=values.shape[0],
                       count=1, dtype=values.dtype, crs=CRS, transform=affine, nodata=nodata) as dst:
        dst.write(values, 1)


# Config source entry with checksum and fixture metadata; used by make_fixture.
def _source(path, dataset_id, **kwargs):
    return {"path": path.name, "sha256": sha256_file(path), "dataset_id": dataset_id,
            "release": "deterministic fixture v1", "license": "project test fixture",
            "citation": "Synthetic fixture generated by science.level2.cgis_level2", **kwargs}


# Writes a CSV with a header row; used by make_fixture.
def _csv(path, headers, rows):
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(headers)
        writer.writerows(rows)


# Writes the fixture into an empty `path` and returns its config.json; used by the CLI and tests.
def make_fixture(path, level1_manifest=None):
    path = Path(path).resolve()
    path.mkdir(parents=True, exist_ok=True)
    if any(path.iterdir()):
        raise ValueError("synthetic output directory must be empty")
    # Exercise the partly masked geographic Level 1 fixture without placing either town over its lake.
    east, north = Transformer.from_crs("EPSG:4326", CRS, always_xy=True).transform(77.06, 12.93)
    x, y = floor(east / PIXEL) * PIXEL, floor(north / PIXEL) * PIXEL
    # Two adjacent towns share a half-cell boundary. A hole and a seam at 256 cells exercise the masks.
    edge = x + 141.5 * PIXEL
    alpha = box(x, y - 180 * PIXEL, edge, y).difference(
        box(x + 15 * PIXEL, y - 35 * PIXEL, x + 30 * PIXEL, y - 20 * PIXEL))
    beta = box(edge, y - 178 * PIXEL, x + 433 * PIXEL, y - 6 * PIXEL)
    items = [("SYN-A", "fixture-alpha", "Fixture Alpha", "synthetic-west", "urban", 12500, alpha),
             ("SYN-B", "fixture-beta", "Fixture Beta", "synthetic-east", "rural", 3250, beta)]
    inverse = Transformer.from_crs(CRS, "EPSG:4326", always_xy=True).transform
    _write_json(path / "study_areas.geojson", {
        "type": "FeatureCollection",
        "features": [{"type": "Feature", "properties": {"census_id": row[0]},
                      "geometry": mapping(transform(inverse, row[-1]))} for row in items],
    })
    _csv(path / "selected.csv", ["census_id", "slug", "name", "region", "morphology", "population_2011"],
         [row[:-1] for row in items])
    _csv(path / "pca.csv", ["census_id", "name", "population_2011"],
         [(row[0], row[2], row[-2]) for row in items])
    rows, cols = np.indices((98, 230))
    labels = np.where((rows // 11 + cols // 15) % 4 == 0, 1, 2).astype("int16")
    labels[9:25, 36:42] = 3
    labels[20:23, 48:51] = -9999
    _write_raster(path / "lulc.tif", labels, Affine(2 * PIXEL, 0, x - 2 * PIXEL, 0, -2 * PIXEL, y + 2 * PIXEL),
                  -9999)
    _write_json(path / "legend.json", {"classes": [
        {"code": 1, "label": "Settlement", "source_value": "BUILT"},
        {"code": 2, "label": "Agriculture", "source_value": "CROP"},
        {"code": 3, "label": "Water", "source_value": "WATER"},
    ]})
    if level1_manifest is None:
        rows, cols = np.indices((50, 115))
        counts = np.where(cols > 2, 12 + (2 * rows + cols) % 12, 0).astype("float32")
        counts[8:14, 9:12] = -99999
        raster_path = path / "level1.tif"
        _write_raster(raster_path, counts, Affine(4 * PIXEL, 0, x - 2.5 * PIXEL, 0, -4 * PIXEL, y + 2.5 * PIXEL),
                      -99999)
        level1_manifest = path / "level1-manifest.json"
        _write_json(level1_manifest, {"manifest_version": 1, "datasets": [{
            "dataset_id": "synthetic-india-l1-pop-2011", "version": 1, "title": "SYNTHETIC Level 1 2011",
            "kind": "raster", "product_level": "level1", "year": 2011, "units": "people_per_cell",
            "source": "SYNTHETIC fixture", "file": raster_path.name, "checksum_sha256": sha256_file(raster_path),
            "provenance": {"synthetic": True},
        }]})
    cfg = path / "config.json"
    level1_manifest = Path(level1_manifest).resolve()
    try:
        level1_path = Path(os.path.relpath(level1_manifest, path)).as_posix()
    except ValueError:  # Separate drives on Windows cannot share a relative path.
        level1_path = level1_manifest.as_posix()
    lulc = _source(path / "lulc.tif", "synthetic-lulc", kind="raster")
    _write_json(cfg, {
        "mode": "synthetic", "version": 1, "output_dir": "outputs", "memory_limit_gib": 2,
        "method": {
            "primary": "hard", "minimum_lulc_coverage": .9, "minimum_level1_coverage": .9,
            "approval_status": "synthetic",
            "class_weights": {"Settlement": {"soft": 1, "hard": True},
                              "Agriculture": {"soft": .15, "hard": False},
                              "Water": {"soft": 0, "hard": False}},
        },
        "sources": {
            "selection": _source(path / "selected.csv", "synthetic-selection"),
            "pca": _source(path / "pca.csv", "synthetic-pca"),
            "boundaries": _source(path / "study_areas.geojson", "synthetic-boundaries"),
            "legend": _source(path / "legend.json", "synthetic-legend"),
            "lulc": {row[1]: lulc for row in items},
            "level1": {"manifest": level1_path,
                       "dataset_id": "synthetic-india-l1-pop-2011", "version": 1},
        },
    })
    return cfg
