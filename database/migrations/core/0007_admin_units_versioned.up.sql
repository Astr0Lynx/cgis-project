-- 0007: version-aware identity for geo.admin_units (completion P1, acceptance row P1).
--
-- Before: unit_id was a global PRIMARY KEY, so importing version 2 of a boundary dataset (or a
-- different boundary dataset reusing a source code) overwrote the geometry of the older version.
--
-- After (additive, backward compatible for readers):
--   * identity   = (dataset_id, dataset_version, unit_id)   UNIQUE NULLS NOT DISTINCT
--                  (rows without a catalog dataset keep a unit_id that is unique among themselves);
--   * primary key = unit_key, a surrogate bigint (a PK cannot contain the nullable dataset columns);
--   * every existing row keeps its values; nothing is deleted or rewritten (no backfill needed:
--     the importer has always filled dataset_id/dataset_version);
--   * geo.current_admin_units: the units of the CURRENT ready version of each dataset, plus
--     units that belong to no dataset. All spatial primitives now read through it, so a
--     withdrawn version (ready -> failed) disappears and the previous ready version is served again;
--   * units of a READY dataset version are immutable (same rule as catalog.datasets rows).
--
-- Re-runnable (test_migration_sql_itself_is_rerunnable): every step checks the current state.

ALTER TABLE geo.admin_units ADD COLUMN IF NOT EXISTS unit_key bigint GENERATED BY DEFAULT AS IDENTITY;
COMMENT ON COLUMN geo.admin_units.unit_key IS
    'Surrogate primary key. Identity of a unit is (dataset_id, dataset_version, unit_id).';

DO $$
DECLARE
    pk_cols text[];
BEGIN
    SELECT array_agg(a.attname ORDER BY k.ord) INTO pk_cols
      FROM pg_constraint c
      JOIN LATERAL unnest(c.conkey) WITH ORDINALITY k(attnum, ord) ON true
      JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.attnum
     WHERE c.conrelid = 'geo.admin_units'::regclass AND c.contype = 'p';
    IF pk_cols IS DISTINCT FROM ARRAY['unit_key']::text[] THEN
        IF pk_cols IS NOT NULL THEN
            ALTER TABLE geo.admin_units DROP CONSTRAINT admin_units_pkey;
        END IF;
        ALTER TABLE geo.admin_units ADD CONSTRAINT admin_units_pkey PRIMARY KEY (unit_key);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'geo.admin_units'::regclass AND conname = 'admin_units_identity') THEN
        ALTER TABLE geo.admin_units ADD CONSTRAINT admin_units_identity
            UNIQUE NULLS NOT DISTINCT (dataset_id, dataset_version, unit_id);
    END IF;
END
$$;

COMMENT ON CONSTRAINT admin_units_identity ON geo.admin_units IS
    'Version-aware unit identity. Its index also serves collection-scoped OGC paging (ORDER BY unit_id).';

-- The identity index (dataset_id, dataset_version, unit_id) covers the old FK lookup index.
DROP INDEX IF EXISTS geo.admin_units_dataset_idx;
CREATE INDEX IF NOT EXISTS admin_units_unit_id_idx ON geo.admin_units (unit_id);

COMMENT ON TABLE geo.admin_units IS
    'Analysis units of every imported dataset VERSION. Identity (dataset_id, dataset_version, unit_id); '
    'geom is a valid 2D MultiPolygon in EPSG:4326. Read current units through geo.current_admin_units.';

-- Units of a ready dataset version are immutable (an identical rewrite is a no-op and allowed, so
-- idempotent re-imports keep working). Withdrawal is done on the catalog row, never on the units.
CREATE OR REPLACE FUNCTION geo.admin_units_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.dataset_id IS NOT NULL
       AND ROW(NEW.unit_id, NEW.name, NEW.level, NEW.geom, NEW.properties, NEW.dataset_id,
               NEW.dataset_version, NEW.source, NEW.provenance)
           IS DISTINCT FROM
           ROW(OLD.unit_id, OLD.name, OLD.level, OLD.geom, OLD.properties, OLD.dataset_id,
               OLD.dataset_version, OLD.source, OLD.provenance)
       AND EXISTS (SELECT 1 FROM catalog.datasets d
                    WHERE d.dataset_id = OLD.dataset_id AND d.version = OLD.dataset_version
                      AND d.status = 'ready')
    THEN
        RAISE EXCEPTION 'unit % of ready dataset %, v% is immutable; import a new dataset version instead',
            OLD.unit_id, OLD.dataset_id, OLD.dataset_version
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END
$$;

CREATE OR REPLACE TRIGGER admin_units_guard
    BEFORE UPDATE ON geo.admin_units
    FOR EACH ROW EXECUTE FUNCTION geo.admin_units_guard();

-- Read surface: units of the current ready version of each dataset, plus dataset-less units.
-- Same public columns as the table (u.*), so it is a drop-in replacement for readers.
CREATE OR REPLACE VIEW geo.current_admin_units AS
SELECT u.*
  FROM geo.admin_units u
 WHERE u.dataset_id IS NULL
    OR EXISTS (
        SELECT 1 FROM catalog.datasets d
         WHERE d.dataset_id = u.dataset_id
           AND d.version = u.dataset_version
           AND d.status = 'ready'
           AND NOT EXISTS (
                SELECT 1 FROM catalog.datasets n
                 WHERE n.dataset_id = d.dataset_id
                   AND n.status = 'ready'
                   AND n.version > d.version));

COMMENT ON VIEW geo.current_admin_units IS
    'Units of the highest READY version of each dataset (catalog.current_datasets) plus units without '
    'a dataset. Older versions stay in geo.admin_units and are listed by geo.dataset_units(id, version).';

-- Units of one dataset: an explicit version, or (p_version NULL) its current ready version.
-- An explicit version is returned whatever its catalog status, so withdrawn or superseded versions
-- remain inspectable; it is the caller's choice to ask for one.
CREATE OR REPLACE FUNCTION geo.dataset_units(p_dataset_id text, p_version integer DEFAULT NULL)
RETURNS SETOF geo.admin_units
LANGUAGE sql STABLE PARALLEL SAFE
AS $$
    SELECT u.*
      FROM geo.admin_units u
     WHERE u.dataset_id = $1
       AND u.dataset_version = coalesce($2, (SELECT c.version FROM catalog.current_datasets c
                                              WHERE c.dataset_id = $1))
     ORDER BY u.unit_id
$$;

-- Every stored version of one unit id within a dataset, newest first, with its catalog status.
CREATE OR REPLACE FUNCTION geo.unit_versions(p_dataset_id text, p_unit_id text)
RETURNS TABLE (dataset_id text, dataset_version integer, unit_id text, name text, level text,
               catalog_status text, is_current boolean, geom geometry)
LANGUAGE sql STABLE PARALLEL SAFE
AS $$
    SELECT u.dataset_id, u.dataset_version, u.unit_id, u.name, u.level, d.status,
           EXISTS (SELECT 1 FROM catalog.current_datasets c
                    WHERE c.dataset_id = u.dataset_id AND c.version = u.dataset_version),
           u.geom
      FROM geo.admin_units u
      JOIN catalog.datasets d ON d.dataset_id = u.dataset_id AND d.version = u.dataset_version
     WHERE u.dataset_id = $1 AND u.unit_id = $2
     ORDER BY u.dataset_version DESC
$$;

-- Normalizing upsert keyed by the version-aware identity. The same unit_id may exist in other
-- datasets and other versions; units of a ready version are protected by geo.admin_units_guard.
CREATE OR REPLACE FUNCTION geo.upsert_admin_unit(
    p_unit_id text,
    p_name text,
    p_level text,
    p_geom geometry,
    p_properties jsonb DEFAULT '{}'::jsonb,
    p_dataset_id text DEFAULT NULL,
    p_dataset_version integer DEFAULT NULL,
    p_source text DEFAULT NULL,
    p_provenance jsonb DEFAULT '{}'::jsonb,
    p_repair boolean DEFAULT false)
RETURNS geo.admin_units
LANGUAGE plpgsql
AS $$
DECLARE
    r geo.admin_units;
BEGIN
    INSERT INTO geo.admin_units AS u (unit_id, name, level, geom, properties,
                                      dataset_id, dataset_version, source, provenance)
    VALUES (p_unit_id, p_name, p_level, geo.normalize_multipolygon(p_geom, p_repair),
            coalesce(p_properties, '{}'::jsonb), p_dataset_id, p_dataset_version,
            p_source, coalesce(p_provenance, '{}'::jsonb))
    ON CONFLICT ON CONSTRAINT admin_units_identity DO UPDATE SET
        name = EXCLUDED.name, level = EXCLUDED.level, geom = EXCLUDED.geom,
        properties = EXCLUDED.properties, source = EXCLUDED.source,
        provenance = EXCLUDED.provenance
    RETURNING * INTO r;
    RETURN r;
END
$$;

-- Spatial primitives (same signatures as 0004) now read the CURRENT units only.
CREATE OR REPLACE FUNCTION geo.units_in_bbox(
    xmin double precision, ymin double precision,
    xmax double precision, ymax double precision,
    srid integer DEFAULT 4326, p_level text DEFAULT NULL)
RETURNS SETOF geo.admin_units
LANGUAGE sql STABLE PARALLEL SAFE
AS $$
    SELECT u.*
      FROM geo.current_admin_units u,
           LATERAL (SELECT cgis.envelope_4326($1, $2, $3, $4, $5) AS env) q
     WHERE u.geom && q.env
       AND ST_Intersects(u.geom, q.env)
       AND ($6 IS NULL OR u.level = $6)
     ORDER BY u.unit_id, u.dataset_id
$$;

CREATE OR REPLACE FUNCTION geo.units_intersecting(g geometry, p_level text DEFAULT NULL)
RETURNS SETOF geo.admin_units
LANGUAGE sql STABLE PARALLEL SAFE
AS $$
    SELECT u.*
      FROM geo.current_admin_units u,
           LATERAL (SELECT cgis.to_4326($1) AS q) t
     WHERE u.geom && t.q
       AND ST_Intersects(u.geom, t.q)
       AND ($2 IS NULL OR u.level = $2)
     ORDER BY u.unit_id, u.dataset_id
$$;

CREATE OR REPLACE FUNCTION geo.units_covered_by(aoi geometry, p_level text DEFAULT NULL)
RETURNS SETOF geo.admin_units
LANGUAGE sql STABLE PARALLEL SAFE
AS $$
    SELECT u.*
      FROM geo.current_admin_units u,
           LATERAL (SELECT cgis.to_4326($1) AS q) t
     WHERE u.geom @ t.q
       AND ST_CoveredBy(u.geom, t.q)
       AND ($2 IS NULL OR u.level = $2)
     ORDER BY u.unit_id, u.dataset_id
$$;

CREATE OR REPLACE FUNCTION geo.unit_overlap(aoi geometry, p_level text DEFAULT NULL)
RETURNS TABLE (unit_id text, name text, level text,
               unit_area_m2 double precision, overlap_area_m2 double precision,
               overlap_fraction double precision)
LANGUAGE sql STABLE PARALLEL SAFE
AS $$
    WITH q AS (SELECT cgis.to_4326($1) AS g),
    hits AS (
        SELECT u.unit_id, u.dataset_id, u.name, u.level,
               ST_Area(u.geom::geography) AS unit_area,
               ST_Area(ST_Intersection(u.geom, q.g)::geography) AS overlap_area
          FROM geo.current_admin_units u, q
         WHERE u.geom && q.g
           AND ST_Intersects(u.geom, q.g)
           AND ($2 IS NULL OR u.level = $2))
    SELECT unit_id, name, level, unit_area, overlap_area,
           CASE WHEN unit_area > 0 THEN overlap_area / unit_area END
      FROM hits
     WHERE overlap_area > 0
     ORDER BY unit_id, dataset_id
$$;

CREATE OR REPLACE FUNCTION geo.summarize_units(aoi geometry DEFAULT NULL)
RETURNS TABLE (level text, unit_count bigint, total_area_m2 double precision,
               extent geometry)
LANGUAGE sql STABLE PARALLEL SAFE
AS $$
    WITH q AS (SELECT CASE WHEN $1 IS NULL THEN NULL ELSE cgis.to_4326($1) END AS g)
    SELECT u.level,
           count(*),
           sum(ST_Area(u.geom::geography)),
           ST_SetSRID(ST_Extent(u.geom)::geometry, 4326)
      FROM geo.current_admin_units u, q
     WHERE q.g IS NULL OR (u.geom && q.g AND ST_Intersects(u.geom, q.g))
     GROUP BY u.level
     ORDER BY u.level NULLS LAST
$$;

